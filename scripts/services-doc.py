#!/usr/bin/env python3
"""Writes docs/SERVICES.md from Core/Catalog.swift, checking each page's status and uptime-history feeds.

Usage: scripts/services-doc.py   (needs network; about a minute)
"""
import datetime
import json
import re
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "Core" / "Catalog.swift"
OUT = ROOT / "docs" / "SERVICES.md"


def get(url):
    req = urllib.request.Request(url, headers={"Accept": "application/json", "User-Agent": "HealthBar-catalog-check"})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return r.status, r.read()
    except urllib.error.HTTPError as e:
        return e.code, b""
    except Exception:
        return None, b""


def check(base):
    """('Statuspage' | 'incident.io' | '?', has history) — the same path the app takes."""
    host = base.split("//", 1)[1]
    status, body = get(base + "/api/v2/summary.json")
    if status != 200:
        return "?", False
    ids = [c["id"] for c in json.loads(body).get("components", []) if not c.get("group")]
    now = datetime.datetime.now(datetime.timezone.utc)
    start = now - datetime.timedelta(days=29)
    q = f"?start_at={start:%Y-%m-%dT%H:%M:%SZ}&end_at={now:%Y-%m-%dT%H:%M:%SZ}"
    status, body = get(f"{base}/proxy/{host}/component_impacts{q}")
    if status == 200:
        return "incident.io", True
    if status != 404:
        return "incident.io", False
    status, body = get(f"{base}/uptime_showcase?components={','.join(ids[:60])}")
    return "Statuspage", status == 200 and bool(json.loads(body or b"{}").get("timelines"))


def main():
    text = CATALOG.read_text()
    groups = re.findall(r'group\("([^"]+)", \[(.*?)\]\)', text, re.S)
    lines = [
        "<!-- Generated by scripts/services-doc.py from Core/Catalog.swift; do not edit by hand. -->",
        "# Built-in services",
        "",
        f"The status pages HealthBar lists in Settings, checked {datetime.date.today():%Y-%m-%d}. "
        "✓ in *Default* means checked on first launch. *History* is whether the page publishes the per-day "
        "data behind the 30-day strip; without it the menu shows “No uptime history”. Any other Statuspage or "
        "incident.io page can be added by its address.",
    ]
    for group, body in groups:
        lines += ["", f"## {group}", "", "| Service | Status page | Platform | Default | History |", "|---|---|---|---|---|"]
        for name, url, on in re.findall(r'\("([^"]+)", "(https://[^"]+)", (true|false)\)', body):
            platform, history = check(url)
            lines.append(f"| {name} | <{url}> | {platform} | {'✓' if on == 'true' else ''} | {'✓' if history else '—'} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
